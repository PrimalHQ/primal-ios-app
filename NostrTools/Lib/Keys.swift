import secp256k1

func bech32_privkey(_ privkey: String) -> String? {
    guard let bytes = hex_decode(privkey) else {
        return nil
    }
    return bech32_encode(hrp: "nsec", bytes)
}

func bech32_pubkey(_ pubkey: String) -> String? {
    guard let bytes = hex_decode(pubkey) else {
        return nil
    }
    return bech32_encode(hrp: "npub", bytes)
}

func bech32_note_id(_ evid: String) -> String? {
    guard let bytes = hex_decode(evid) else {
        return nil
    }
    return bech32_encode(hrp: "note", bytes)
}

func bech32_lnurl(_ url: String) -> String? {
    guard let data = url.data(using: .utf8) else { return nil}
    return bech32_encode(hrp: "lnurl", [UInt8](data))
}

func bech32_article_id(_ evid: String) -> String? {
    guard let bytes = hex_decode(evid) else { return nil }
    return bech32_encode(hrp: "naddr", bytes)
}

func privkey_to_pubkey(privkey: String) -> String? {
    guard let sec = hex_decode(privkey) else {
        return nil
    }
    guard let key = try? secp256k1.Schnorr.PrivateKey(dataRepresentation: sec) else {
        return nil
    }
    return hex_encode(Data(key.xonly.bytes))
}
