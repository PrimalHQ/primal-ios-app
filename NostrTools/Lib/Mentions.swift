struct ReferencedId: Identifiable, Hashable, Equatable {
    let ref_id: String
    let relay_id: String?
    let key: String
    
    var id: String {
        return ref_id
    }
}

func tag_to_refid(_ tag: [String]) -> ReferencedId? {
    if tag.count == 0 {
        return nil
    }
    if tag.count == 1 {
        return nil
    }
    
    var relay_id: String? = nil
    if tag.count > 2 {
        relay_id = tag[2]
    }
    
    return ReferencedId(ref_id: tag[1], relay_id: relay_id, key: tag[0])
}

enum MentionType {
    case pubkey
    case event
}

struct Mention: Equatable {
    let index: Int?
    let type: MentionType
    let ref: ReferencedId
}

typealias Invoice = LightningInvoice

enum InvoiceDescription {
    case description(String)
    case description_hash(Data)
}

struct LightningInvoice {
    let description: String
    let amount: UInt64?
    let string: String
    let expiry: UInt64
    let created_at: UInt64
}
